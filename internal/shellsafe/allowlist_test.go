func FuzzAllowedUnderImplGuard(f *testing.F) {
	for _, s := range []string{"", "make test", "go test ./...", "echo x > f", "git -c a=b log", "a <<EOF\nx\nEOF", "$(", "'", "make \x00", "go build -o /dev/null ."} {
		f.Add(s)
	}
	f.Fuzz(func(t *testing.T, cmd string) {
		_ = AllowedUnderImplGuard(cmd)
		_ = AllowedUnderImplGuardPowerShell(cmd)
	})
}
